def test_generate_all_ui_descriptors():
    """End-to-end orchestration: every root + every shared category file
    gets its own <ClassName>.ui.json, dispatch maps resolve to real files,
    and labels are merged across the whole set."""
    import tempfile
    from inkind_knowledge_repo.generators.ui_descriptor import generate_all_ui_descriptors

    schema_path = "src/inkind_knowledge_repo/schema/inkind_knowledge_repo.yaml"

    with tempfile.TemporaryDirectory() as tmp_dir:
        generate_all_ui_descriptors(schema_path, tmp_dir, roots=("DonationItem",))

        donation_item_path = os.path.join(tmp_dir, "DonationItem.ui.json")
        assert os.path.exists(donation_item_path)
        with open(donation_item_path, encoding="utf-8") as f:
            donation_item = json.load(f)

        category_field = next(f for f in donation_item["fields"] if f["name"] == "category")
        dispatch_map = category_field["dispatches_to"]
        assert len(dispatch_map) == 16

        # Every dispatched file must actually have been written, and be
        # self-describing (its own "class" key matches the target filename).
        for category_value, filename in dispatch_map.items():
            target_path = os.path.join(tmp_dir, filename)
            assert os.path.exists(target_path), f"{filename} (for {category_value}) was not generated"
            with open(target_path, encoding="utf-8") as f:
                target = json.load(f)
            assert target["class"] == filename.removesuffix(".ui.json")

        for locale in ("en", "de"):
            labels_path = os.path.join(tmp_dir, f"labels-{locale}.json")
            assert os.path.exists(labels_path)
            with open(labels_path, encoding="utf-8") as f:
                labels = json.load(f)
            assert "DonationItem" in labels
            assert "ClothingPhysicalItemMixin" in labels


def test_ui_descriptor_donation_item_real_subclasses_still_validate():
    """DonationItem's real concrete subclasses (used by gen-pydantic, not by
    UI-descriptor dispatch after the category descriptor sync work) must
    still carry their own category's *ContextRulesMixin lc-* rules via their
    mixin ancestry, so real data validation isn't regressed by moving lc-*
    rules out of donation_item.yaml and into categories/_context_rules.yaml.

    Tier 3 is one mixin PER CATEGORY (not a single universal mixin — an
    earlier version used one, which caused cross-category rule leakage via
    shared field names like "subcategory"; see _context_rules.yaml's header),
    so each subclass is checked against its own category-specific mixin."""
    sv = SchemaView(SCHEMA_PATH)

    subclass_to_context_mixin = {
        "ClothingItem": "ClothingContextRulesMixin",
        "AccessoriesItem": "AccessoriesContextRulesMixin",
        "FootwearItem": "FootwearContextRulesMixin",
        "FurnitureItem": "FurnitureContextRulesMixin",
        "BeddingTextilesItem": "BeddingContextRulesMixin",
        "HouseholdItem": "HouseholdContextRulesMixin",
        "ElectronicsItem": "ElectronicsContextRulesMixin",
        "ToysItem": "ToysContextRulesMixin",
        "SportsItem": "SportsContextRulesMixin",
        "BooksItem": "BooksContextRulesMixin",
        "StationeryItem": "StationeryContextRulesMixin",
        "PersonalCareItem": "PersonalCareContextRulesMixin",
        "MobilityAidsItem": "MobilityAidsContextRulesMixin",
        "BabyInfantItem": "BabyInfantContextRulesMixin",
        "FoodItem": "FoodContextRulesMixin",
        "OtherItem": "OtherContextRulesMixin",
    }
    for cls, context_mixin in subclass_to_context_mixin.items():
        ancestors = sv.class_ancestors(cls)
        assert context_mixin in ancestors, (
            f"{cls} lost {context_mixin} — real data validation would no "
            f"longer enforce its lc-* rules"
        )
        # No OTHER category's context mixin should leak in.
        other_context_mixins = set(subclass_to_context_mixin.values()) - {context_mixin}
        leaked = other_context_mixins & set(ancestors)
        assert not leaked, f"{cls} unexpectedly carries unrelated context mixins: {leaked}"

        rule_titles = set()
        for ancestor in ancestors:
            ancestor_cls = sv.get_class(ancestor)
            for rule in getattr(ancestor_cls, "rules", []) or []:
                rule_titles.add(rule.title)
        assert any(t.startswith("lc-") for t in rule_titles), (
            f"{cls} has no lc-* rules reachable via its ancestor chain"
        )

    # DemandSignal's bare Tier 1 dispatch targets must NEVER pick up any
    # Tier 3 content, from any category.
    demand_targets = ["ClothingCategory", "FurnitureCategory", "MobilityAidsCategory"]
    all_context_mixins = set(subclass_to_context_mixin.values())
    for cls in demand_targets:
        ancestors = set(sv.class_ancestors(cls))
        leaked = all_context_mixins & ancestors
        assert not leaked, (
            f"{cls} (a DemandSignal dispatch target) unexpectedly carries "
            f"Tier 3 lc-* rules: {leaked}"
        )


def test_ui_descriptor_no_cross_category_rule_leakage():
    """Regression test for a real bug found during implementation: a single
    universal Tier 3 mixin caused lc-* rules from one category to attach to
    same-named fields (e.g. "subcategory") in unrelated categories. Confirm
    Furniture's subcategory field — which has no lc-* rule of its own — never
    picks up a visible_when from Clothing/Baby/Sports's subcategory-required
    rules, which share the same target field name."""
    gen = UiDescriptorGenerator(SCHEMA_PATH, top_class="FurnitureAssessmentMixin")
    furniture = gen.generate()["FurnitureAssessmentMixin"]
    subcategory = next(f for f in furniture["fields"] if f["name"] == "subcategory")
    assert "visible_when" not in subcategory


def test_ui_descriptor_labels_resolve_via_ancestor_walk_from_tier1_mixin():
    """label_en/label_de/aliases_en/aliases_de are declared on each category's
    Tier 1 mixin (e.g. FurnitureCategory) and also mirrored onto DonationItem's
    real concrete subclasses (e.g. FurnitureItem) for alias_generator.py, which
    walks sv.all_classes() directly rather than through the UI descriptor's
    dispatch targets. The UI descriptor generator itself never introspects
    those concrete subclasses — it resolves labels for its own dispatch
    targets (the bare Tier 1 mixin and the physical-item mixin that is_a's it)
    via _get_class_label_annotations' ancestor walk, independent of whatever
    the concrete subclass carries."""
    gen = UiDescriptorGenerator(SCHEMA_PATH, top_class="DonationItem")

    bare = gen._get_class_label_annotations("FurnitureCategory")
    physical = gen._get_class_label_annotations("FurnitureAssessmentMixin")
    assert bare.get("label_en").value == "Furniture"
    assert physical.get("label_en").value == "Furniture"
    assert bare.get("label_de").value == physical.get("label_de").value == "Möbel"

    # A category with no Tier 2 split still resolves for both its own bare
    # mixin and its trivial physical-item composition class.
    clothing_bare = gen._get_class_label_annotations("ClothingCategory")
    clothing_physical = gen._get_class_label_annotations("ClothingPhysicalItemMixin")
    assert clothing_bare.get("label_en").value == "Clothing"
    assert clothing_physical.get("label_en").value == "Clothing"

    # DonationItem's real concrete subclasses carry the same label, kept in
    # sync with their Tier 1 mixin, for alias_generator.py's benefit.
    sv = SchemaView(SCHEMA_PATH)
    clothing_item_cls = sv.get_class("ClothingItem")
    clothing_item_anns = getattr(clothing_item_cls, "annotations", None) or {}
    assert clothing_item_anns.get("label_en").value == "Clothing"


