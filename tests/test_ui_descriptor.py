def test_ui_descriptor_demand_signal_structure():
    """DemandSignal dispatches to bare Tier 1 files only: no assessment_result
    anywhere, no lc-*-derived visible_when anywhere, and the
    PersonalCareSubcategoryEnum drift the design doc flagged is resolved
    automatically since DemandSignal now reuses the one canonical enum."""
    demand = _generate("DemandSignal")
    dispatch_map = _dispatch_map(demand)
    assert len(dispatch_map) == 16

    sv = SchemaView(SCHEMA_PATH)
    assert sv.get_class("AnyValue") is None

    for category_value, filename in dispatch_map.items():
        target_class = filename.removesuffix(".ui.json")
        target = _generate(target_class)
        for field in target["fields"]:
            assert field["name"] != "assessment_result", (
                f"DemandSignal's {category_value} dispatch target unexpectedly "
                f"has assessment_result"
            )
            visible_when = field.get("visible_when", {})
            assert "lifecycle_state" not in visible_when, (
                f"DemandSignal's {category_value}.{field['name']} unexpectedly "
                f"has lifecycle_state-gated visibility"
            )

    personal_care = _generate("PersonalCareCategory")
    subcategory_values = personal_care["enums"]["PersonalCareSubcategoryEnum"]
    assert "sanitary_products" in subcategory_values
    assert "incontinence_products" in subcategory_values
    assert "nappies_incontinence" not in subcategory_values
